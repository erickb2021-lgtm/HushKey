"""Builds brand_data.py: the app-logo list and the Poppins font, stored inside
a Python file instead of as separate data files.

Why: Python files are ALWAYS packed into the Mac and Windows apps, while
separate data files can be left out if the build is set up slightly wrong.
Keeping them inside code means the logos and font can never go missing.

Run from the project folder after changing assets/brand_icons.json.gz or the
fonts:   python packaging/embed_data.py
"""
import base64
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")


def b64(path):
    with open(os.path.join(ROOT, path), "rb") as f:
        return base64.b64encode(f.read()).decode("ascii")


def main():
    lines = [
        '"""Generated by packaging/embed_data.py - do not edit by hand.',
        "",
        "The app-logo list (Simple Icons, CC0) and the Poppins font (SIL OFL),",
        'stored inside code so they are always packed into the apps."""',
        "",
        "BRAND_ICONS_GZ_B64 = (",
    ]
    data = b64("assets/brand_icons.json.gz")
    for i in range(0, len(data), 120):
        lines.append(f'    "{data[i:i + 120]}"')
    lines.append(")")
    lines.append("")
    lines.append("FONTS_B64 = {")
    for name in ("Poppins-Regular.ttf", "Poppins-Bold.ttf"):
        data = b64(f"assets/fonts/{name}")
        lines.append(f'    "{name}": (')
        for i in range(0, len(data), 120):
            lines.append(f'        "{data[i:i + 120]}"')
        lines.append("    ),")
    lines.append("}")
    out = os.path.join(ROOT, "app", "brand_data.py")
    with open(out, "w", encoding="ascii") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", os.path.abspath(out), os.path.getsize(out) // 1024, "KB")


if __name__ == "__main__":
    main()
